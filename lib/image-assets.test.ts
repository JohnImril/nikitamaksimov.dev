import { readdirSync, readFileSync, statSync } from "node:fs";
import path from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { cleanup, render } from "@testing-library/react";
import WorkPage, {
  generateMetadata,
  generateStaticParams,
} from "@/app/work/[slug]/page";
import { SITE_ORIGIN } from "./metadata";

afterEach(cleanup);

function expectLocalImage(source: string) {
  const url = new URL(source, SITE_ORIGIN);
  if (url.origin !== SITE_ORIGIN) return;
  if (url.pathname === "/_next/image") {
    expectLocalImage(url.searchParams.get("url")!);
    return;
  }
  // This image is generated by an App Router endpoint, not stored in public.
  const filename =
    url.pathname === "/opengraph-image"
      ? "app/opengraph-image.tsx"
      : `public${decodeURIComponent(url.pathname)}`;
  expect({
    source,
    exists: statSync(path.resolve(filename), {
      throwIfNoEntry: false,
    })?.isFile(),
  }).toEqual({ source, exists: true });
}

describe("local image assets", () => {
  it("resolves image literals in content, metadata, components and CSS", () => {
    expect.hasAssertions();
    for (const root of ["content", "app", "components", "lib"]) {
      for (const file of readdirSync(root, {
        recursive: true,
        encoding: "utf8",
      })) {
        if (!/\.(tsx?|css)$/.test(file) || file.endsWith(".test.ts")) continue;
        const source = readFileSync(path.join(root, file), "utf8");
        for (const match of source.matchAll(
          /["'`(](\/(?!\/)[^"'`()\s$]*\.(?:webp|png|jpe?g|svg|avif|gif|ico)(?:\?[^"'`()\s]*)?)/g,
        )) {
          expectLocalImage(match[1]);
        }
      }
    }
  });

  for (const { slug } of generateStaticParams()) {
    it(`resolves rendered images, full-size links and social images for ${slug}`, async () => {
      const params = Promise.resolve({ slug });
      const metadata = await generateMetadata({ params });
      for (const images of [
        metadata.openGraph?.images,
        metadata.twitter?.images,
      ]) {
        expect(Array.isArray(images)).toBe(true);
        if (!Array.isArray(images))
          throw new Error("Expected social image array");
        expect(images.length).toBeGreaterThan(0);
        for (const image of images) {
          expectLocalImage(
            typeof image === "string"
              ? image
              : image instanceof URL
                ? image.href
                : image.url.toString(),
          );
        }
      }
      const { container } = render(await WorkPage({ params }));
      for (const image of container.querySelectorAll("img")) {
        expectLocalImage(image.getAttribute("src")!);
      }
      for (const link of container.querySelectorAll("a[href]")) {
        const href = link.getAttribute("href")!;
        if (/\.(webp|png|jpe?g|svg|avif)(?:\?|$)/.test(href))
          expectLocalImage(href);
      }
      for (const script of container.querySelectorAll(
        'script[type="application/ld+json"]',
      )) {
        const data = JSON.parse(script.textContent);
        if (data.image) expectLocalImage(data.image);
      }
    });
  }
});
